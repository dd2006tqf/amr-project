#!/usr/bin/env bash
# C++ 编译器启动器：在真正的编译命令里注入 GCC 的内存回收参数。
#
# ============================================================================
# 解决什么
# ============================================================================
# 单个 cc1plus 在本项目的模板密集 TU（dispatcher_node / map_ingest_node /
# vda5050_gateway_node）上峰值 RSS 达 1.5–2 GB，主要不是「实例化出来的代码
# 太占内存」，而是 **GCC 自己的 GC 堆**：GCC 默认让内部 GC 堆长到相当大才
# 回收，这在内存充裕的机器上是纯收益（少回收 = 快），在 3.7 GB 机器上则是
# 灾难——峰值直接决定会不会进 swap 颠簸。
#
#   --param ggc-min-expand=10      降低「堆增长多少 % 才回收」的门槛
#   --param ggc-min-heapsize=32768 堆超过 32 MB 就开始积极回收
#
# 代价是编译变慢（回收次数变多），换的是峰值下降。构建脚本已按内存把并发
# 压到 1，本启动器是第二道保险 —— 单进程也要能装进内存。
#
# ============================================================================
# 为什么用启动器而不是 CMake 编译选项
# ============================================================================
# 这两个参数只在**编译**阶段有意义。通过 CMAKE_CXX_FLAGS 注入会同时混进
# 链接命令行；通过 CMAKE_CXX_COMPILER_LAUNCHER 注入则只影响编译调用，
# 对 colcon 和所有子项目的 CMakeLists.txt 都透明 —— 不需要改任何一个包。
#
# 用法：
#   export CMAKE_CXX_COMPILER_LAUNCHER=/path/to/scripts/gcc_mem_guard.sh
#
# 未设置 AMR_GCC_MEM_GUARD=1 时本脚本完全透明（等价于直接 exec），
# 因此可以无条件挂上去而不改变默认构建行为。
#
# ============================================================================
# ccache 协同
# ============================================================================
# 本仓库宿主机装了 ccache，容器里没有。若启用 ccache，必须让 ccache 位于
# **最外层**：命中缓存时它根本不会调用编译器，也就不会带上 GC 参数；未命中
# 时才真正编译。这样缓存键与「不使用本脚本」时逐字相同，历史缓存继续有效。
# 若反过来把 ccache 放在内层，GC 参数会进入缓存键，导致全量缓存失效。

set -u

GCC_MEM_PARAMS=(--param ggc-min-expand=10 --param ggc-min-heapsize=32768)

# 无参数（理论上不会发生）：原样退出，避免 set -u 下的下标错误。
if [ "$#" -eq 0 ]; then
  exit 1
fi

compiler="$1"
shift

if [ "${AMR_GCC_MEM_GUARD:-0}" != "1" ]; then
  # 透明模式：原样透传，不注入任何参数。
  if command -v ccache >/dev/null 2>&1; then
    exec ccache "$compiler" "$@"
  fi
  exec "$compiler" "$@"
fi

# 参数紧跟编译器名插入：GCC 接受选项出现在任意位置，但紧跟其后最不容易
# 被后续的 `-o` / `-c` 解析逻辑误伤，也最接近手写命令行的习惯。
if command -v ccache >/dev/null 2>&1; then
  exec ccache "$compiler" "${GCC_MEM_PARAMS[@]}" "$@"
fi

exec "$compiler" "${GCC_MEM_PARAMS[@]}" "$@"
